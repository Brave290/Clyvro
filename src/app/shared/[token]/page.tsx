import Link from "next/link";
import type { Metadata } from "next";
import { detailToScanReport, getSharedAudit } from "@/lib/services/audits";
import ReportView from "@/components/ReportView";
import { ShieldAlert } from "lucide-react";

export const dynamic = "force-dynamic";
export const metadata: Metadata = {
  title: "Shared audit report | Clyvro",
  description: "A read-only Clyvro audit report shared by link.",
  robots: { index: false, follow: false },
};

export default async function SharedReportPage({ params }: { params: Promise<{ token: string }> }) {
  const { token } = await params;
  const detail = await getSharedAudit(token);

  if (!detail) {
    return (
      <div className="mx-auto max-w-3xl px-5 py-16">
        <div className="rounded-2xl border border-warn/30 bg-warn-soft p-8 text-center" role="alert">
          <ShieldAlert size={28} className="mx-auto text-warn" aria-hidden />
          <h1 className="mt-3 text-2xl font-bold">This report link isn&apos;t available</h1>
          <p className="mx-auto mt-2 max-w-md text-sm leading-relaxed text-ink-soft">
            The link may have expired or been revoked by its owner. Ask them to create a fresh
            share link from their Clyvro dashboard.
          </p>
          <p className="mt-4 text-sm">
            <Link href="/scan" className="font-semibold text-accent hover:underline">Run your own scan →</Link>
          </p>
        </div>
      </div>
    );
  }

  const report = detailToScanReport(detail);

  return (
    <div className="mx-auto max-w-5xl px-5 py-10">
      <p className="inline-flex items-center gap-2 rounded-full border border-line bg-surface px-3 py-1 text-xs font-semibold text-ink-soft">
        Shared read-only report — generated by Clyvro
      </p>
      <ReportView report={report} contextNote="shared report" />
      <p className="mt-8 text-center text-sm text-ink-soft">
        Want your own audit? <Link href="/scan" className="font-semibold text-accent hover:underline">Run a free scan</Link>{" "}
        or <Link href="/sign-up" className="font-semibold text-accent hover:underline">create an account</Link> to save and compare audits.
      </p>
    </div>
  );
}
