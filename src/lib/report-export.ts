import type { ScanReport } from "@/lib/scanner/types";
import { confidenceLabel, type Finding, type Severity } from "@/lib/types";

/**
 * Agent-ready report exports. Same honesty rules as the UI: the score
 * is an internal prioritisation number (not revenue/conversion), every
 * finding keeps its rule id, confidence basis and evidence, and the
 * coverage/limitations sections say plainly what was NOT checked.
 */

const SEVERITY_ORDER: Severity[] = ["critical", "high", "medium", "low"];

function sortedFindings(report: ScanReport): Finding[] {
  return [...report.findings].sort(
    (a, b) => SEVERITY_ORDER.indexOf(a.severity) - SEVERITY_ORDER.indexOf(b.severity),
  );
}

function severityCounts(report: ScanReport): string {
  return SEVERITY_ORDER
    .map((s) => `${report.findings.filter((f) => f.severity === s).length} ${s}`)
    .join(", ");
}

function coverageLines(report: ScanReport): string[] {
  const c = report.coverage;
  return [
    `- Pages fetched: ${c.pagesFetched} (read in full: ${c.pagesParsed}, limit ${c.maxPages}, depth ${c.maxDepth})`,
    `- Links discovered: ${c.linksDiscovered}; verified: ${c.linksChecked}; not verified: ${c.linksUnchecked}`,
    `- Form destinations verified (never submitted): ${c.formDestinationsChecked}`,
    `- Skipped by robots.txt: ${c.skippedByRobots}; truncated pages: ${c.truncatedPages}`,
    `- Time limit hit: ${c.deadlineHit ? "yes — results are partial" : "no"}`,
  ];
}

export function reportFileSlug(report: ScanReport): string {
  let host = "website";
  try {
    host = new URL(report.finalUrl ?? report.target).hostname.replace(/^www\./, "");
  } catch {
    /* keep fallback */
  }
  const date = report.startedAt.slice(0, 10);
  return `clyvro-scan-${host}-${date}`;
}

/** Full report as Markdown (the "README" download). */
export function reportToMarkdown(report: ScanReport): string {
  const lines: string[] = [];
  lines.push(`# Clyvro website check — ${report.finalUrl ?? report.target}`);
  lines.push("");
  lines.push(`- Scanned: ${report.startedAt} (${(report.durationMs / 1000).toFixed(1)}s), ruleset v${report.rulesetVersion}`);
  lines.push(`- Status: ${report.status}`);
  if (report.auditTypes?.length) lines.push(`- Audit types: ${report.auditTypes.join(", ")}`);
  lines.push(
    `- Internal score: ${report.score ?? "n/a"} / 100 — a prioritisation aid from the findings below; not a conversion rate or revenue estimate.`,
  );
  lines.push(`- Findings: ${report.findings.length} (${severityCounts(report)})`);
  if (report.tech?.length) {
    lines.push("");
    lines.push("## Detected technology");
    lines.push("Publicly observable signals only; inferred framework dependencies are labelled.");
    for (const t of report.tech) lines.push(`- ${t.name} (${t.category}; ${t.confidence}) — ${t.evidence}`);
  }
  lines.push("");
  lines.push("## Coverage");
  lines.push(...coverageLines(report));
  if (report.limitations.length) {
    lines.push("");
    lines.push("## Limitations — what this check does not prove");
    for (const l of report.limitations) lines.push(`- ${l}`);
  }
  lines.push("");
  lines.push("## Findings (most severe first)");
  if (report.findings.length === 0) {
    lines.push("");
    lines.push("No issues found within the coverage above. That is not a guarantee the site is issue-free — see Limitations.");
  }
  sortedFindings(report).forEach((f, i) => {
    lines.push("");
    lines.push(`### ${i + 1}. [${f.severity.toUpperCase()}] ${f.title}`);
    lines.push(`- Rule: \`${f.ruleId}\` v${f.ruleVersion} · Category: ${f.category} · ${confidenceLabel(f.confidenceBasis)}`);
    lines.push(`- Page: ${f.page}`);
    lines.push(`- Why it matters: ${f.explanation}`);
    lines.push(`- Impact: ${f.impactRationale}`);
    lines.push(`- Evidence:`);
    for (const e of f.evidence) lines.push(`  - ${e}`);
    lines.push(`- Fix: ${f.recommendation} (typical effort: ${f.effort.toLowerCase()})`);
  });
  if (report.pages.length) {
    lines.push("");
    lines.push("## Pages read");
    for (const p of report.pages) lines.push(`- ${p.url} — HTTP ${p.status}${p.title ? ` — “${p.title}”` : ""}`);
  }
  lines.push("");
  lines.push("---");
  lines.push("Generated by Clyvro — Find the friction. Fix the conversion. Evidence-first: every finding above was directly observed or is labelled heuristic; re-scan after fixing to verify.");
  return lines.join("\n");
}

/**
 * A prefilled brief to paste to an AI coding agent or developer.
 * Instructions only — the agent must fix and re-verify, and any
 * repository write still needs the owner's explicit approval.
 */
export function reportToAgentBrief(report: ScanReport): string {
  const site = report.finalUrl ?? report.target;
  const lines: string[] = [];
  lines.push(`You are fixing issues found by an evidence-based website audit of ${site} (scanned ${report.startedAt}, status ${report.status}).`);
  lines.push("");
  lines.push("Rules:");
  lines.push("1. Fix only the issues listed below, in the order given (most severe first). Do not redesign unrelated pages.");
  lines.push("2. The evidence quotes are what the scanner directly observed — verify each issue exists in the current code/markup before changing anything; if you cannot reproduce one, say so instead of guessing.");
  lines.push("3. After each fix, state how it can be verified (reload the page / re-run the audit).");
  lines.push("4. Do not commit or push anything without my explicit approval — show me the diff first.");
  lines.push("");
  lines.push(`Coverage of the audit: ${coverageLines(report).map((l) => l.replace(/^- /, "")).join("; ")}.`);
  if (report.tech?.length) {
    lines.push(`Detected technology (public signals only): ${report.tech.map((t) => `${t.name} [${t.category}, ${t.confidence}]`).join(", ")}.`);
  }
  if (report.limitations.length) lines.push(`Known limitations: ${report.limitations.join(" ")}`);
  lines.push("");
  if (report.findings.length === 0) {
    lines.push("The audit found no issues within its coverage. No fixes requested — just confirm the site still matches the scanned pages.");
    return lines.join("\n");
  }
  lines.push("Issues to fix:");
  sortedFindings(report).forEach((f, i) => {
    lines.push("");
    lines.push(`${i + 1}. [${f.severity.toUpperCase()} · ${confidenceLabel(f.confidenceBasis)}] ${f.title}`);
    lines.push(`   Page: ${f.page} (rule ${f.ruleId} v${f.ruleVersion})`);
    lines.push(`   Why: ${f.explanation} ${f.impactRationale}`);
    lines.push(`   Evidence: ${f.evidence.join(" | ")}`);
    lines.push(`   Fix: ${f.recommendation} (typical effort: ${f.effort.toLowerCase()})`);
  });
  lines.push("");
  lines.push("When done, summarize each change (file + what changed), then ask me before committing. I will re-run the Clyvro scan to verify the fixes.");
  return lines.join("\n");
}
