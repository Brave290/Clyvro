/**
 * AI-Pattern & Generic-ness — shared types + pure content builders.
 * Kept free of database/server imports so the client page and the
 * server service produce byte-identical exports.
 */

export interface AiSignal {
  id: string;
  label: string;
  /** Contribution to the pattern score when present (0–100 scale total). */
  weight: number;
  evidence: string[];
  advice: string;
}

export type AiBand = "low" | "moderate" | "high";

export interface AiPatternReport {
  domain: string;
  finalUrl: string | null;
  /** Pattern-likelihood 0–100. NOT a probability of AI authorship. */
  score: number;
  band: AiBand;
  signals: AiSignal[];
  guardChecklist: string[];
  stats: { words: number; headings: number; clicheHits: number; uniqueCtas: number };
  limitations: string[];
}

export const AI_BAND_LABEL: Record<AiBand, string> = {
  low: "Low generic-pattern match — the copy reads mostly specific",
  moderate: "Moderate generic-pattern match — several sections read templated",
  high: "High generic-pattern match — much of the page reads like unedited generic output",
};

export function aiPatternToMarkdown(report: AiPatternReport): string {
  const lines: string[] = [];
  lines.push(`# AI-Pattern & Generic-ness report — ${report.domain}`);
  lines.push("");
  lines.push(`- Page analysed: ${report.finalUrl ?? `https://${report.domain}`}`);
  lines.push(`- Pattern-likelihood score: ${report.score}/100 — ${AI_BAND_LABEL[report.band]}`);
  lines.push("- Important: this is a pattern match against known generic AI/template signals. It is NOT proof of who or what wrote the site.");
  lines.push(`- Homepage stats: ${report.stats.words} words · ${report.stats.headings} headings · ${report.stats.clicheHits} flagged phrases · ${report.stats.uniqueCtas} distinct CTA labels`);
  lines.push("");
  lines.push("## Signals found");
  if (!report.signals.length) lines.push("No generic-pattern signals were detected on the homepage. Keep it that way with the guard checklist below.");
  for (const s of report.signals) {
    lines.push("");
    lines.push(`### ${s.label} (+${s.weight})`);
    for (const e of s.evidence) lines.push(`- Evidence: ${e}`);
    lines.push(`- Do: ${s.advice}`);
  }
  lines.push("");
  lines.push("## Guard checklist — staying un-generic");
  for (const g of report.guardChecklist) lines.push(`- [ ] ${g}`);
  lines.push("");
  lines.push("## Limitations");
  for (const l of report.limitations) lines.push(`- ${l}`);
  lines.push("");
  lines.push("---");
  lines.push("Generated by Clyvro — Find the friction. Fix the conversion. Re-run after edits to verify the pattern score falls because the copy got more specific.");
  return lines.join("\n");
}

/** The full, ready-to-paste de-genericize prompt for the owner's AI agent/developer. */
export function aiPatternToAgentPrompt(report: AiPatternReport): string {
  const lines: string[] = [];
  lines.push(`You are de-genericizing the website ${report.finalUrl ?? `https://${report.domain}`}. An evidence-based pattern analysis (Clyvro AI-Pattern detector) scored its homepage copy/structure at ${report.score}/100 for similarity to generic AI/template output — ${AI_BAND_LABEL[report.band]}. Your job is to make the copy unmistakably specific to THIS business. It is not about hiding AI use; it is about replacing vague filler with true, verifiable specifics.`);
  lines.push("");
  lines.push("Hard rules:");
  lines.push("1. Never invent facts. Where a specific fact is needed and you don't have it, insert a clearly-marked placeholder like [ADD: founding year] and list all placeholders at the end for the owner to fill in.");
  lines.push("2. Keep every true claim already on the page. Change wording and structure, not the business's actual offers, prices, or identity.");
  lines.push("3. Show your edits section by section (before → after) and wait for my approval before committing or publishing anything.");
  lines.push("");
  if (report.signals.length) {
    lines.push("Fix these detected generic-pattern signals, in this order:");
    report.signals.forEach((s, i) => {
      lines.push("");
      lines.push(`${i + 1}. ${s.label}`);
      lines.push(`   Evidence from the live page: ${s.evidence.join(" | ")}`);
      lines.push(`   Direction: ${s.advice}`);
    });
    lines.push("");
  } else {
    lines.push("No strong generic signals were detected. Still do a specificity pass: check every heading could only describe this business, and add proof (names, numbers, dates) wherever a claim is made.");
    lines.push("");
  }
  lines.push("Style targets for the rewrite:");
  lines.push("- Every heading must fail the swap test: if a competitor could paste it unchanged, rewrite it.");
  lines.push("- Replace superlatives (best, leading, world-class) with the evidence behind them, or delete them.");
  lines.push("- Each call-to-action names its destination and payoff; no repeated “Get Started / Learn More” labels.");
  lines.push("- Prefer short, concrete sentences: who, what, where, since when, how much, what happened for a real customer (only with permission).");
  lines.push("- Keep the page's structure and design system; this is a copy mission, not a redesign.");
  lines.push("");
  lines.push("When done, list: (1) each section changed with before/after, (2) every [ADD: …] placeholder needing a real fact from me, (3) anything you intentionally left alone. I will re-run the Clyvro AI-Pattern detector to verify the score fell because the copy became more specific.");
  return lines.join("\n");
}
