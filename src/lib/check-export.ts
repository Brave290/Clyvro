/**
 * Agent-ready exports for the check-list surfaces (Readiness, Hack
 * Protection, SEO Visibility) and the Developer Tools — same honesty
 * contract as the scanner exports: observed facts only, fix steps kept,
 * and limitations stated instead of implied guarantees.
 */

export interface CheckItemLike {
  id: string;
  group: string;
  label: string;
  status: "pass" | "warn" | "fail" | "info";
  detail: string;
  fix?: string[];
}

export interface DevResultLike {
  tool: string;
  target: string;
  facts: { label: string; value: string; status?: string }[];
  sections: { title: string; items: string[] }[];
}

const STATUS_WORD: Record<CheckItemLike["status"], string> = {
  pass: "PASS", warn: "IMPROVE", fail: "FAILING", info: "INFO",
};

export function checkReportToMarkdown(title: string, subject: string, checks: CheckItemLike[], extra: string[] = []): string {
  const lines: string[] = [`# ${title} — ${subject}`, ""];
  const counts = (s: CheckItemLike["status"]) => checks.filter((c) => c.status === s).length;
  lines.push(`- ${counts("pass")} passed · ${counts("warn")} to improve · ${counts("fail")} failing (of ${checks.length} checks)`);
  for (const e of extra) lines.push(`- ${e}`);
  const groups = [...new Set(checks.map((c) => c.group))];
  for (const g of groups) {
    lines.push("", `## ${g}`);
    for (const c of checks.filter((x) => x.group === g)) {
      lines.push(`- [${STATUS_WORD[c.status]}] ${c.label} — ${c.detail}`);
      if (c.fix?.length && c.status !== "pass") lines.push(`  Fix: ${c.fix.join(" → ")}`);
    }
  }
  lines.push("", "---", "Generated by Clyvro — Find the friction. Fix the conversion. Every line above is an observed fact; re-run after fixing to verify.");
  return lines.join("\n");
}

export function checkReportToAgentBrief(title: string, subject: string, checks: CheckItemLike[], extra: string[] = []): string {
  const lines: string[] = [];
  lines.push(`You are fixing issues found by ${title} for ${subject}. Work only from the observed facts below.`);
  lines.push("");
  lines.push("Rules:");
  lines.push("1. Fix the FAILING items first, then IMPROVE items, in the order given. Do not change anything that passed.");
  lines.push("2. Each item states what was directly observed — verify it in the current code/config before changing anything; if you can't reproduce it, say so.");
  lines.push("3. After each fix, state how it can be verified. Do not commit or push without my explicit approval.");
  for (const e of extra) lines.push(`Note: ${e}`);
  const work = checks.filter((c) => c.status === "fail" || c.status === "warn");
  lines.push("");
  if (!work.length) {
    lines.push("Everything checked passed. No fixes requested — confirm nothing regressed.");
    return lines.join("\n");
  }
  lines.push("Items to fix:");
  work.forEach((c, i) => {
    lines.push("");
    lines.push(`${i + 1}. [${STATUS_WORD[c.status]} · ${c.group}] ${c.label}`);
    lines.push(`   Observed: ${c.detail}`);
    if (c.fix?.length) lines.push(`   Fix: ${c.fix.join(" → ")}`);
  });
  lines.push("");
  lines.push("When done, summarize each change and ask me before committing. I will re-run the check to verify.");
  return lines.join("\n");
}

export function devToolToMarkdown(title: string, result: DevResultLike): string {
  const lines: string[] = [`# ${title} — ${result.target}`, "", "## Facts"];
  for (const f of result.facts) lines.push(`- ${f.label}: ${f.value}${f.status && f.status !== "info" ? ` (${f.status})` : ""}`);
  for (const s of result.sections) {
    lines.push("", `## ${s.title}`);
    for (const item of s.items) lines.push(`- ${item}`);
  }
  lines.push("", "---", "Generated by Clyvro — facts read live from the target at run time.");
  return lines.join("\n");
}

export function devToolToAgentBrief(title: string, result: DevResultLike): string {
  const lines: string[] = [];
  lines.push(`Context: I ran ${title} on ${result.target} with Clyvro. Facts observed:`);
  for (const f of result.facts) lines.push(`- ${f.label}: ${f.value}`);
  for (const s of result.sections) {
    lines.push("", `${s.title}:`);
    for (const item of s.items) lines.push(`- ${item}`);
  }
  lines.push("");
  lines.push("Help me act on anything marked warn/fail above. Verify each fact against my current setup before changing anything, propose the smallest safe change, and wait for my approval before committing.");
  return lines.join("\n");
}

export function exportSlug(kind: string, subject: string): string {
  let host = subject;
  try {
    host = new URL(subject.includes("://") ? subject : `https://${subject}`).hostname.replace(/^www\./, "");
  } catch { /* keep raw subject */ }
  return `clyvro-${kind}-${host || "website"}-${new Date().toISOString().slice(0, 10)}`;
}
